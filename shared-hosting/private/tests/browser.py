import json,pathlib
from playwright.sync_api import sync_playwright
project=pathlib.Path(__file__).resolve().parents[2]; root=project/'private'/'test-output'; root.mkdir(exist_ok=True); checks=[]; errors=[]
with sync_playwright() as p:
 b=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox'])
 page=b.new_page(viewport={'width':1440,'height':1000})
 page.on('pageerror',lambda e:errors.append(str(e)))
 page.route('https://images.unsplash.com/**',lambda r:r.abort())
 requests=[];page.on('request',lambda r:requests.append(r.url))
 def check(name,fn):
  try: fn();checks.append({'name':name,'passed':True})
  except Exception as e: checks.append({'name':name,'passed':False,'error':str(e)[:500]})
 def yes(v):
  if not v:raise AssertionError('assertion failed')
 def route(r):
  page.evaluate('(r)=>location.hash=r',r);page.wait_for_timeout(200)
 def start():
  page.set_content('<!doctype html><html lang="en"><head><meta name="viewport" content="width=device-width,initial-scale=1"></head><body data-preview="true"><div id="app"></div><dialog id="dialog" aria-labelledby="dialog-title"></dialog><div id="toast" role="status" hidden></div></body></html>')
  page.add_style_tag(content=(project/'public/assets/workspace.css').read_text())
  page.add_script_tag(content=(project/'public/assets/demo.js').read_text())
  page.add_script_tag(content=next((project/'public/assets').glob('template-catalog.*.js')).read_text())
  page.add_script_tag(content=(project/'public/assets/templates.js').read_text())
  page.add_script_tag(content=(project/'public/assets/workspace.js').read_text())
  page.wait_for_selector('h1')
 start()
 check('preview is explicitly marked sample data',lambda:yes('Sample data' in page.inner_text('body')))
 route('contacts');page.locator('[data-action="import"]').click() if page.locator('[data-action="import"]').count() else page.locator('[data-action="import-contacts"]').click()
 page.wait_for_selector('dialog[open]')
 check('import dialog opens',lambda:yes(page.locator('dialog[open]').count()==1))
 page.locator('#import-group').select_option(index=1)
 check('new group field is hidden for an existing group',lambda:yes(not page.locator('#new-group-field').is_visible()))
 page.locator('#dialog [data-action="close-dialog"]').last.click()
 check('Cancel does not submit or navigate the form',lambda:yes(page.locator('dialog[open]').count()==0 and page.locator('h1').inner_text()=='Contacts'))
 route('verification');page.locator('[data-action="job-detail"]').first.click()
 check('verified import has exactly one visible submission button',lambda:yes(page.get_by_role('button',name='Add verified contacts',exact=True).count()==1))
 page.locator('#verified-group').select_option(index=1)
 check('verified import new-group field hides correctly',lambda:yes(not page.locator('#valid-new-group').is_visible()))
 page.keyboard.press('Escape');check('Escape closes verification dialog',lambda:yes(page.locator('dialog[open]').count()==0))
 # Parser exercises the actual production parser, not the demo API.
 def parse(text):return page.evaluate('async (t)=>{let a=[];for await (let r of SendzadCSV.records(t))a.push(r);return a}',text)
 check('CSV handles BOM, quoted comma and escaped quote',lambda:yes(parse('\ufeffemail,name\r\na@example.net,"A, B"\r\nb@example.net,"A ""quote"""')==[['email','name'],['a@example.net','A, B'],['b@example.net','A "quote"']]))
 check('CSV handles multiline quoted cells',lambda:yes(parse('email,name\na@example.net,"A\nB"')==[['email','name'],['a@example.net','A\nB']]))
 check('CSV accepts an empty trailing column',lambda:yes(parse('a@example.net,')==[['a@example.net','']]))
 def badcsv():
  r=page.evaluate('async()=>{try{for await(let x of SendzadCSV.records(\'"unclosed\')){}return false}catch{return true}}');yes(r)
 check('CSV rejects an unclosed quoted field',badcsv)
 def largecsv():
  yes(page.evaluate('async()=>{let count=0;let t="email\\n"+Array.from({length:50001},(_,i)=>`person${i}@example.net`).join("\\n");for await(let r of SendzadCSV.records(new Blob([t])))count++;return count}')==50002)
 check('50,001 addresses stream through the real CSV parser',largecsv)
 route('templates');page.locator('[data-action="use-template"]').first.click();page.wait_for_timeout(250)
 check('template opens the content editor',lambda:yes('composer' in page.evaluate('location.hash') and page.locator('iframe').count()==1))
 check('editor iframe cannot execute scripts',lambda:yes('allow-scripts' not in (page.locator('iframe').get_attribute('sandbox')or'')))
 # Exercise the full client workflow with the explicitly synthetic preview API.
 page.locator('#draft-name').fill('QA draft')
 page.locator('#draft-subject').fill('QA subject')
 page.locator('[data-action="editor-mode"][data-value="source"]').click()
 page.locator('#html-source').fill('<p>QA retained content</p><script>window.parent.bad=1</script>')
 page.locator('[data-action="editor-mode"][data-value="visual"]').click()
 page.wait_for_timeout(150)
 check('editor strips executable content before rendering',lambda:yes(page.locator('#email-frame').evaluate('(f)=>f.contentDocument.querySelectorAll("script").length')==0))
 page.locator('[data-action="editor-mode"][data-value="source"]').click()
 check('mode switching preserves edited content',lambda:yes('QA retained content' in page.locator('#html-source').input_value()))
 page.locator('[data-action="save-continue"]').click()
 page.wait_for_selector('input[name="launch-group"]')
 check('saving advances to audience selection',lambda:yes(page.locator('h1').inner_text()=='Choose your audience'))
 page.locator('input[name="launch-group"]').first.check()
 page.locator('input[name="launch-account"]').first.check()
 page.locator('#send-interval').fill('7')
 page.locator('[data-action="wizard-review"]').click()
 page.wait_for_selector('#launch-consent')
 check('review retains the selected sending interval',lambda:yes('7 seconds' in page.inner_text('#main')))
 check('launch is blocked until explicit permission confirmation',lambda:yes(page.locator('#launch-button').is_disabled()))
 page.locator('#launch-consent').check()
 check('launch becomes available after explicit confirmation',lambda:yes(page.locator('#launch-button').is_enabled()))
 page.locator('[data-action="open-test"]').click()
 page.wait_for_selector('dialog[open]')
 check('single-address test dialog creates a stable opaque request ID',lambda:yes(len(page.locator('input[name="request_id"]').input_value())==32))
 page.locator('#dialog input[name="email"]').fill('qa@example.net')
 page.locator('#dialog select[name="account_id"]').select_option(index=1)
 page.locator('#dialog button[type="submit"]').click()
 page.wait_for_timeout(150)
 check('design preview refuses actual sending',lambda:yes('No messages were sent' in page.locator('#dialog-error').inner_text()))
 page.keyboard.press('Escape')
 page.set_viewport_size({'width':768,'height':950});route('overview')
 check('tablet sidebar remains interactive',lambda:yes(not page.locator('#sidebar').evaluate('(e)=>e.inert')))
 # Accessibility/viewport checks across the full workspace.
 for width in [360,390,768,1024,1440]:
  page.set_viewport_size({'width':width,'height':950})
  for r in ['overview','campaigns','contacts','verification','templates','reports','senders','settings','composer','report/00000000000000000000000000000001']:
   route(r)
   check(f'{width}px {r.split("/")[0]} has no document overflow',lambda:yes(page.evaluate('document.documentElement.scrollWidth<=innerWidth')))
 page.set_viewport_size({'width':390,'height':844});route('overview')
 page.locator('[data-action="open-nav"]').click()
 check('mobile navigation opens',lambda:yes('open' in page.locator('#sidebar').get_attribute('class')))
 page.keyboard.press('Escape')
 check('Escape dismisses mobile navigation',lambda:yes('open' not in page.locator('#sidebar').get_attribute('class')))
 check('no JavaScript page errors',lambda:yes(not errors))
 check('only approved photo URL attempts; fetches blocked',lambda:yes(all(u.startswith(('about:','data:','blob:','https://images.unsplash.com/')) for u in requests)))
 result={'checks':len(checks),'passed':sum(c['passed']for c in checks),'failed':sum(not c['passed']for c in checks),'page_errors':errors,'requests':requests,'results':checks}
 (root/'ui-interaction-results.json').write_text(json.dumps(result,indent=2))
 print(json.dumps({k:v for k,v in result.items()if k!='results'},indent=2))
 print(json.dumps([c for c in checks if not c['passed']],indent=2))
 b.close()
