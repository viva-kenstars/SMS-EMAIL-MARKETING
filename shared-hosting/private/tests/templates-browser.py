"""Offline template/UI verification. Never submits provider requests or real messages."""
import json
from pathlib import Path
from playwright.sync_api import sync_playwright

project = Path(__file__).resolve().parents[2]
out = project / 'private' / 'test-output' / 'templates'
out.mkdir(parents=True, exist_ok=True)
checks, errors, requests = [], [], []

def yes(value, message='Assertion failed'):
    if not value:
        raise AssertionError(message)

def check(name, run):
    try:
        run()
        checks.append({'name': name, 'passed': True})
    except Exception as exc:
        checks.append({'name': name, 'passed': False, 'error': str(exc)[:900]})

with sync_playwright() as p:
    browser = p.chromium.launch(executable_path='/usr/bin/chromium', headless=True, args=['--no-sandbox'])
    context = browser.new_context(viewport={'width':1440, 'height':1040}, reduced_motion='reduce')
    context.route('**/*', lambda route: route.abort())
    page = context.new_page()
    page.set_default_timeout(6000)
    page.on('pageerror', lambda e: errors.append(str(e)))
    page.on('request', lambda r: requests.append(r.url))
    page.set_content('<!doctype html><html lang="en"><head><meta name="viewport" content="width=device-width,initial-scale=1"></head><body data-preview="true"><div id="app"></div><dialog id="dialog" aria-labelledby="dialog-title"></dialog><div id="toast" role="status" hidden></div></body></html>')
    page.add_style_tag(content=(project/'public/assets/workspace.css').read_text())
    page.add_script_tag(content=next((project/'public/assets').glob('template-catalog.*.js')).read_text())
    for filename in ['demo.js','templates.js','workspace.js']:
        page.add_script_tag(content=(project/'public/assets'/filename).read_text())
    page.wait_for_selector('h1')
    def route(name):
        page.evaluate('(r)=>location.hash=r',name)
        page.wait_for_timeout(140)
    def close():
        if page.locator('dialog[open]').count():
            page.keyboard.press('Escape')
    def evaluate(expression):
        return page.evaluate(expression)
    evaluate('SendzadTemplates.load()')
    ids=evaluate('SendzadTemplates.templates.map(t=>t.id)')
    check('16 original designs with stable unique IDs',lambda:yes(len(ids)==16 and len(set(ids))==16))
    check('10 business and six commerce designs',lambda:yes(evaluate('[SendzadTemplates.templates.filter(t=>t.collection==="Business").length,SendzadTemplates.templates.filter(t=>t.collection==="Commerce").length]')==[10,6]))
    check('10 reusable section types',lambda:yes(evaluate('SendzadTemplates.blocks.length')==10))
    check('all designs have one managed header, footer and main content target',lambda:yes(evaluate('SendzadTemplates.templates.every(t=>{const d=new DOMParser().parseFromString(t.html,"text/html");return ["header","footer"].every(k=>d.querySelectorAll(`[data-tz-${k}="standard"]`).length===1)&&d.querySelectorAll("[data-tz-content=main]").length===1})')))
    check('all layout tables are presentation tables',lambda:yes(evaluate('SendzadTemplates.templates.every(t=>{const d=new DOMParser().parseFromString(t.html,"text/html");return [...d.querySelectorAll("table")].every(x=>x.getAttribute("role")==="presentation")})')))
    check('all built-ins below 95 KB',lambda:yes(evaluate('SendzadTemplates.templates.every(t=>new TextEncoder().encode(t.html).length<95000)')))
    check('no executable dependencies in built-in email markup',lambda:yes(evaluate('SendzadTemplates.templates.every(t=>!new DOMParser().parseFromString(t.html,"text/html").querySelector("script,link,iframe,object,embed"))')))
    check('plain-text generator preserves links, removes managed footer and markup',lambda:yes(evaluate('(()=>{let s=SendzadTemplates.toText(SendzadTemplates.get("newsletter").html);return s.includes("https://example.com/replace/story")&&!s.includes("<table")&&!s.includes("Unsubscribe")&&!s.includes("{{postal_address}}")&&s.includes("\\n")})()')))
    check('minimal footer does not invent social or preference pages',lambda:yes(evaluate('(()=>{const d=new DOMParser().parseFromString(SendzadTemplates.footer({name:"Actual brand",postal_address:"Real business address"}),"text/html");return d.querySelectorAll("a").length===1&&d.querySelector("a").textContent==="Unsubscribe"})()')))
    check('optional footer links are rendered when configured',lambda:yes(evaluate('(()=>{const h=SendzadTemplates.footer({name:"Brand",postal_address:"Address",support_email:"support@sendzad.com",phone:"+234 000",privacy_url:"https://sendzad.com/privacy",preferences_url:"https://sendzad.com/preferences",facebook_url:"https://facebook.com/brand",instagram_url:"https://instagram.com/brand",linkedin_url:"https://linkedin.com/company/brand"});let d=new DOMParser().parseFromString(h,"text/html");return d.querySelectorAll("a").length===7&&d.body.textContent.includes("+234 000")})()')))
    check('brand copy is HTML escaped; non-HTTPS links omitted',lambda:yes(evaluate('(()=>{let h=SendzadTemplates.footer({name:"<img src=x onerror=alert(1)>",website:"javascript:alert(1)",postal_address:"A & B",facebook_url:"javascript:alert(1)"});let d=new DOMParser().parseFromString(h,"text/html");return !d.querySelector("img")&&!h.includes("href=\\"javascript:")&&h.includes("A &amp; B")})()')))
    check('module normalization removes duplicate header and footer',lambda:yes(evaluate('(()=>{let t=SendzadTemplates.get("welcome");let h=SendzadTemplates.prepare(t.html+new DOMParser().parseFromString(t.html,"text/html").querySelector("[data-tz-header]").outerHTML+new DOMParser().parseFromString(t.html,"text/html").querySelector("[data-tz-footer]").outerHTML,{brand:{name:"Brand",postal_address:"Address"}});let d=new DOMParser().parseFromString(h,"text/html");return d.querySelectorAll("[data-tz-header]").length===1&&d.querySelectorAll("[data-tz-footer]").length===1})()')))
    check('editing serialization retains brand tokens, not preview identity',lambda:yes(evaluate('(()=>{let L=SendzadTemplates;let d=new DOMParser().parseFromString(L.prepare(L.get("welcome").html,{brand:{name:"PreviewOnlyBrand",postal_address:"PreviewOnlyAddress"},editing:true}),"text/html");let s=L.serialize(d);return s.includes("{{brand_name}}")&&s.includes("{{postal_address}}")&&!s.includes("PreviewOnlyAddress")&&!s.includes("PreviewOnlyBrand")})()')))
    check('preflight blocks sample product copy and example links',lambda:yes(evaluate('(()=>{let L=SendzadTemplates,r=L.preflight(L.create("catalog"),{name:"Sendzad",website:"https://sendzad.com",postal_address:"Address"});return !r.ready&&r.errors.some(x=>x.includes("bracketed"))&&r.warnings.some(x=>x.includes("photographs"))&&r.errors.some(x=>x.includes("example-domain"))})()')))
    check('preflight allows a reviewed welcome with complete branding',lambda:yes(evaluate('SendzadTemplates.preflight(SendzadTemplates.create("welcome"),{name:"Sendzad",website:"https://sendzad.com",postal_address:"Address"}).ready')))
    check('preflight rejects unsupported merge fields',lambda:yes(evaluate('!SendzadTemplates.preflight({subject:"Hi {{secret}}",html:"<p>Hello</p>",text_body:"Hi",preheader:"News"},{name:"Brand",postal_address:"Address"}).ready')))
    check('preflight rejects example social destinations',lambda:yes(evaluate('!SendzadTemplates.preflight({subject:"Hi",html:"<p>Hello</p>",text_body:"Hi",preheader:"News"},{name:"Brand",postal_address:"Address",instagram_url:"https://example.com/profile"}).ready')))
    check('preflight warns about empty preheader and plain text',lambda:yes(evaluate('SendzadTemplates.preflight({subject:"Hi",html:"<p>Hello</p>"},{name:"Brand",postal_address:"Address"}).warnings.length')==2))
    route('templates')
    check('gallery shows all 16 real design cards',lambda:yes(page.locator('.professional-template').count()==16 and page.locator('iframe[data-template-thumb]').count()==16))
    def collections():
        page.locator('[data-action="template-collection"][data-value="Commerce"]').click()
        yes(page.locator('.professional-template').count()==6)
        page.locator('[data-action="template-collection"][data-value="Business"]').click()
        yes(page.locator('.professional-template').count()==10)
        page.locator('[data-action="template-collection"][data-value="All"]').click()
    check('collection filters show six commerce or ten business designs',collections)
    def search():
        page.locator('#template-search').fill('editorial')
        page.wait_for_function('document.querySelectorAll(".professional-template").length===1')
        yes(page.locator('.professional-template').count()==1)
        page.locator('#template-search').fill('no-such-template')
        page.wait_for_function('document.querySelectorAll(".professional-template").length===0')
        yes(page.get_by_text('No designs found',exact=True).count()==1)
        page.locator('#template-search').fill('')
        page.wait_for_function('document.querySelectorAll(".professional-template").length===16')
        page.locator('#template-category').select_option(label='Welcome')
        yes(page.locator('.professional-template').count()==1)
        page.locator('#template-category').select_option(label='All categories')
    check('search, no-results and category filters',search)
    page.wait_for_timeout(600)
    page.screenshot(path=str(out/'library-desktop.png'),full_page=False)
    for width in [360,390,768,1024,1440]:
        page.set_viewport_size({'width':width,'height':950})
        page.wait_for_timeout(100)
        check(f'{width}px library has no page overflow',lambda:yes(evaluate('document.documentElement.scrollWidth<=innerWidth')))
    page.set_viewport_size({'width':390,'height':844});page.screenshot(path=str(out/'library-mobile.png'))
    page.set_viewport_size({'width':1440,'height':1000})
    page.locator('#main [data-action="preview-template"][data-value="welcome"]').click()
    page.wait_for_selector('#template-full-preview')
    check('full preview has subject, preheader and no send controls',lambda:yes('Suggested subject' in page.inner_text('#dialog') and page.locator('#dialog [data-action="launch"]').count()==0))
    check('preview sandbox disallows scripts and parent access',lambda:yes(page.locator('#template-full-preview').get_attribute('sandbox')==''))
    page.locator('[data-action="template-device"][data-value="mobile"]').click()
    check('mobile preview width fits narrow screens',lambda:yes(page.locator('#template-full-preview').bounding_box()['width']<=390))
    close()
    # Actual HTML rendered by the same preview function at multiple viewport widths.
    # Access an automation-created about:blank page; no HTTP host/auth bypass.
    email_page=context.new_page()
    email_page.on('pageerror',lambda e:errors.append(str(e)))
    email_page.on('request',lambda r:requests.append(r.url))
    for tid in ids:
        data=evaluate(f'SendzadTemplates.get({json.dumps(tid)})')
        html=page.evaluate('(id)=>{const L=SendzadTemplates,t=L.get(id);return "<!doctype html><html lang=en><head><meta name=viewport content=\\"width=device-width,initial-scale=1\\"><style>body{margin:0;padding:0}"+L.css+"</style></head><body>"+L.prepare(t.html,{brand:{name:"Sendzad",website:"https://sendzad.com",postal_address:"Sample business address - preview only"},preheader:t.preheader})+"</body></html>"}',tid)
        for width in [320,360,390,640]:
            email_page.set_viewport_size({'width':width,'height':950})
            email_page.set_content(html)
            check(f'{tid} email fits {width}px viewport',lambda:yes(email_page.evaluate('document.documentElement.scrollWidth<=innerWidth'),f'{tid}: overflow'))
            check(f'{tid} has one visible footer at {width}px',lambda:yes(email_page.locator('[data-tz-footer]').count()==1 and email_page.locator('[data-tz-footer]').is_visible()))
        if tid in ['welcome','newsletter','catalog','event','commerce-vendor','commerce-manufacturer']:
            email_page.set_viewport_size({'width':680,'height':1000})
            email_page.screenshot(path=str(out/f'{tid}-email.png'),full_page=True)
        if tid=='welcome':
            email_page.set_viewport_size({'width':390,'height':950});email_page.screenshot(path=str(out/'welcome-mobile.png'),full_page=True)
    email_page.close()
    route('templates')
    page.locator('#main [data-action="use-template"][data-value="welcome"]').click()
    page.wait_for_selector('#email-frame');page.wait_for_timeout(200)
    check('Use template sets suggested subject and preheader',lambda:yes(page.locator('#draft-subject').input_value()=='Welcome to {{brand_name}}' and bool(page.locator('#draft-preheader').input_value())))
    check('new campaign has a populated plain-text alternative',lambda:yes('Hi {{first_name}}' in page.locator('#draft-text').input_value()))
    check('editor header and footer are managed read-only modules',lambda:yes(page.locator('#email-frame').evaluate('(f)=>[...f.contentDocument.querySelectorAll("[data-tz-header],[data-tz-footer]")].every(x=>x.contentEditable==="false")')))
    check('editor has trusted responsive rules',lambda:yes(page.locator('#email-frame').evaluate('(f)=>f.contentDocument.head.textContent.includes("max-width:640px")')))
    def block_insert():
        before=page.locator('#email-frame').evaluate('(f)=>f.contentDocument.querySelectorAll("[data-tz-block]").length')
        page.locator('[data-action="add-section"]').click()
        page.locator('[data-action="add-block"]').first.click()
        page.wait_for_timeout(100)
        after=page.locator('#email-frame').evaluate('(f)=>f.contentDocument.querySelectorAll("[data-tz-block]").length')
        yes(after>before)
        yes(page.locator('#email-frame').evaluate('(f)=>{const d=f.contentDocument;return d.querySelectorAll("[data-tz-footer]").length===1&&(d.querySelector("[data-tz-content]").compareDocumentPosition(d.querySelector("[data-tz-footer]"))&4)!==0}'))
    check('reusable section inserts into content before the single footer',block_insert)
    close()
    def source_roundtrip():
        page.locator('[data-action="editor-mode"][data-value="source"]').click()
        value=page.locator('#html-source').input_value()
        yes('{{brand_name}}' in value and 'Sample address - design preview only' not in value)
        page.locator('[data-action="editor-mode"][data-value="visual"]').click()
        page.wait_for_timeout(100)
        yes(page.locator('#email-frame').evaluate('(f)=>f.contentDocument.querySelectorAll("[data-tz-footer]").length===1'))
    check('source round-trip keeps canonical header/footer and avoids baked-in sample address',source_roundtrip)
    def change_design():
        page.locator('#draft-name').fill('Saved campaign name')
        page.locator('#draft-subject').fill('Preserved subject')
        page.locator('summary[aria-label="Draft actions"]').click()
        page.locator('[data-action="choose-template"]').click()
        page.once('dialog',lambda d:d.accept())
        page.locator('#dialog [data-action="use-template"][data-value="catalog"]').click()
        page.wait_for_timeout(150)
        yes(page.locator('#draft-name').input_value()=='Saved campaign name')
        yes(page.locator('#draft-subject').input_value()=='Preserved subject')
        yes(page.locator('#email-frame').evaluate('(f)=>f.contentDocument.querySelectorAll("img[data-sz-image=stock]").length')==4)
    check('replacing a design confirms and keeps campaign identity',change_design)
    close()
    def remove_image():
        page.once('dialog',lambda d:d.accept(''))
        frame=page.frame_locator('#email-frame')
        frame.locator('img[data-sz-image="stock"]').first.click()
        yes(page.locator('#email-frame').evaluate('(f)=>f.contentDocument.querySelectorAll("img[data-sz-image=stock]").length')==3)
    check('stock photograph can be removed without leaving a broken image',remove_image)
    close()
    def blocked_review():
        page.locator('[data-action="save-continue"]').click()
        page.wait_for_selector('input[name="launch-group"]')
        page.locator('input[name="launch-account"]').first.check()
        page.locator('input[name="launch-group"]').first.check()
        page.locator('[data-action="wizard-review"]').click()
        page.wait_for_selector('#launch-consent')
        page.locator('#launch-consent').check()
        yes(page.locator('#launch-button').is_disabled())
        yes('Content needs attention' in page.inner_text('#main'))
    check('consent cannot bypass unresolved template launch checks',blocked_review)
    close();route('settings')
    def brand_settings():
        page.locator('input[name="brand_name"]').fill('Studio & Co')
        page.locator('input[name="brand_website"]').fill('https://sendzad.com')
        page.locator('textarea[name="postal_address"]').fill('Sample studio address - QA only')
        page.locator('input[name="brand_support_email"]').fill('support@sendzad.com')
        page.frame_locator('#brand-footer-preview').get_by_text('Studio & Co',exact=True).wait_for(state='visible')
        frame=page.frame_locator('#brand-footer-preview')
        yes(frame.get_by_text('Studio & Co',exact=True).count()==1)
        page.locator('button[form="settings-form"]').click()
        page.wait_for_timeout(100)
        route('templates')
        page.locator('#main [data-action="preview-template"][data-value="welcome"]').click()
        page.wait_for_selector('#template-full-preview')
        yes(page.frame_locator('#template-full-preview').locator('[data-tz-header]').inner_text().startswith('Studio & Co'))
    check('brand settings persist in demo and update subsequent previews',brand_settings)
    close()
    check('no uncaught JavaScript errors',lambda:yes(not errors,str(errors)))
    check('only approved photo URL attempts; fetches blocked',lambda:yes(all(x.startswith(('about:','blob:','data:','https://images.unsplash.com/')) for x in requests),str(requests[:5])))
    result={'checks':len(checks),'passed':sum(c['passed'] for c in checks),'failed':sum(not c['passed'] for c in checks),'page_errors':errors,'requests':requests,'results':checks}
    (out/'results.json').write_text(json.dumps(result,indent=2))
    print(json.dumps({k:v for k,v in result.items() if k!='results'},indent=2))
    print(json.dumps([x for x in checks if not x['passed']],indent=2))
    browser.close()
    raise SystemExit(1 if result['failed'] else 0)
