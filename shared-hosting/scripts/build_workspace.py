#!/usr/bin/env python3
"""Build the workspace entry from editable base + explicit extension hook.
Refuse unknown source rather than silently patching an incompatible release.
"""
from pathlib import Path
root=Path(__file__).resolve().parents[1]
s=(root/'public/assets/workspace.js').read_text()
def replace(old,new):
 global s
 if s.count(old)!=1:raise RuntimeError('Workspace integration anchor changed: '+old[:90])
 s=s.replace(old,new)
replace("['senders','Sending accounts','server'],['settings','Settings','settings']", "['email-settings','Email settings','settings']")
replace("const group=['composer','audience','review'].includes(active)?", "const group=active==='template-editor'?'templates':['email-settings','settings','senders'].includes(active)?'email-settings':['composer','audience','review'].includes(active)?")
replace("    const [route,id]=S.route.split('/');S.data=null;\n    try{", "    const [route,id]=S.route.split('/');S.data=null;\n    try{\n        if(await window.SendzadEnterprise.route({route,id,seq,S,api,head,icon,btn,E,N,D,DT,health,nav,render,senders,LIB,ensureBrand,modal,previewHTML,toast}))return;")
# An ordinary save remains a campaign save. Reusable template authoring has its own route.
replace('<button data-action="choose-template">Change template</button>', '<button data-action="choose-template">Change starter design</button><a href="#templates">Saved templates</a>')
s=s.replace('<div class="brand-mark" aria-hidden="true">t</div>', '<div class="brand-mark" aria-hidden="true">s</div>').replace('<div class="brand-mark">t</div>', '<div class="brand-mark">s</div>')
(root/'public/assets/workspace-enterprise.js').write_text('/* Generated by scripts/build_workspace.py. */\n'+s)
print('Enterprise workspace generated; original workspace.js preserved.')
